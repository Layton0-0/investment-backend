-- 전략 거버넌스 2차: 검사 결과 이력 및 (market, strategy_type)별 halt.
CREATE TABLE IF NOT EXISTS TB_GOVERNANCE_CHECK_RESULT (
    ID BIGSERIAL PRIMARY KEY,
    RUN_AT TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MARKET VARCHAR(10) NOT NULL,
    STRATEGY_TYPE VARCHAR(32) NOT NULL,
    MDD_PCT NUMERIC(10, 4),
    SHARPE_RATIO NUMERIC(10, 4),
    DEGRADED VARCHAR(1) NOT NULL DEFAULT 'N',
    START_DATE DATE NOT NULL,
    END_DATE DATE NOT NULL,
    CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_TB_GOVERNANCE_CHECK_RESULT_RUN_AT ON TB_GOVERNANCE_CHECK_RESULT (RUN_AT DESC);
CREATE INDEX IF NOT EXISTS IDX_TB_GOVERNANCE_CHECK_RESULT_MARKET_TYPE ON TB_GOVERNANCE_CHECK_RESULT (MARKET, STRATEGY_TYPE);

COMMENT ON TABLE TB_GOVERNANCE_CHECK_RESULT IS '전략 거버넌스 검사 결과 이력 (회차별 market·strategy_type·메트릭)';
COMMENT ON COLUMN TB_GOVERNANCE_CHECK_RESULT.DEGRADED IS 'Y=열화, N=정상';

CREATE TABLE IF NOT EXISTS TB_GOVERNANCE_HALT (
    MARKET VARCHAR(10) NOT NULL,
    STRATEGY_TYPE VARCHAR(32) NOT NULL,
    HALTED_AT TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    REASON VARCHAR(500),
    CLEARED_AT TIMESTAMPTZ,
    CLEARED_BY VARCHAR(64),
    PRIMARY KEY (MARKET, STRATEGY_TYPE)
);

COMMENT ON TABLE TB_GOVERNANCE_HALT IS '전략 거버넌스: (market, strategy_type)별 자동 매매 중단. CLEARED_AT IS NULL 이면 활성 halt';
